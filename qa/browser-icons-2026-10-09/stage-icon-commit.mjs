import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const run=(args,input)=>execFileSync('git',args,{encoding:'utf8',input});
assert.equal(run(['diff','--cached','--name-only']).trim(),'','Index contains pre-existing changes');
const files=['Dockerfile','branding/build.mjs','branding/browser-icons.mjs','branding/company-logo.mjs','branding/spanvision-infra-curved-s-logo.png','deployment/browser-identity.mjs','deployment/browser-icons','qa/browser-icons-2026-10-09/README.md','qa/browser-icons-2026-10-09/verify-local.mjs'];
run(['add','--',...files]);
let text=run(['show','HEAD:deployment/package-vercel.mjs']);
const importAnchor="import { fileURLToPath } from 'node:url';";
assert(text.includes(importAnchor));
text=text.replace(importAnchor,importAnchor+"\nimport { installBrowserIdentity } from './browser-identity.mjs';");
const anchor="await fs.cp(source, staticDir, { recursive: true, filter: sourcePath => !sourcePath.endsWith('.map') && path.basename(sourcePath) !== 'suite-build.json' });";
assert(text.includes(anchor),'Packaging source anchor changed');
text=text.replace(anchor,anchor+"\nif(id !== 'hub') await installBrowserIdentity(staticDir,{entries:[id === 'cad' ? 'app/index.html' : 'index.html']});");
const blob=run(['hash-object','-w','--stdin'],text).trim();
run(['update-index','--cacheinfo','100644',blob,'deployment/package-vercel.mjs']);
const staged=run(['diff','--cached','--name-only']).trim().split('\n');
assert(staged.every(file=>files.includes(file)||file.startsWith('deployment/browser-icons/')||file==='deployment/package-vercel.mjs'));
console.log(run(['diff','--cached','--stat']));
console.log(run(['diff','--cached','--','deployment/package-vercel.mjs']));
