import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import pngToIco from 'png-to-ico';
const app=path.resolve(import.meta.dirname,'..');
const svg=fs.readFileSync(path.join(app,'public/icon.svg'),'utf8');
fs.writeFileSync(path.join(app,'public/icon.svg'),svg);
const png=await sharp(Buffer.from(svg)).resize(1024).png().toBuffer();
fs.writeFileSync(path.join(app,'public/icon.png'),png);
fs.writeFileSync(path.join(app,'../mcpb/icon.png'),png);
fs.writeFileSync(path.join(app,'src-tauri/icons/icon-new.svg'),svg);
fs.writeFileSync(path.join(app,'src-tauri/icons/icon-new-preview.png'),png);
fs.writeFileSync(path.join(app,'src-tauri/icons/file-icon.png'),png);
for(const size of [16,32,48,64,128,256]) await sharp(png).resize(size).png().toFile(path.join(app,`src-tauri/icons/file-icon-${size}.png`));
await sharp(png).resize(256).png().toFile(path.join(app,'../snap/gui/open-pdf-studio.png'));
const ico=await pngToIco(await sharp(png).resize(256).png().toBuffer());
for (const file of ['public/favicon.ico','public/icon.ico','src-tauri/icons/file-icon.ico']) fs.writeFileSync(path.join(app,file),ico);
const notice=fs.readFileSync(path.join(app,'../docs/legal/ATTRIBUTION.md'),'utf8')+'\n\n'+fs.readFileSync(path.join(app,'../LICENSE.md'),'utf8');
fs.writeFileSync(path.join(app,'public/notices.md'),notice);
console.log('GW icon master, favicon, file icon, and bundled notices created.');
